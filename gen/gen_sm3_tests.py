# 生成 sm3 全量向量测试（数据来自 gen/vectors.json，与 Python gmssl 交叉验证）
import json

vec = json.load(open(r"C:\Users\16841\WorkBuddy\2026-09-17-21-36-22\smcrypto\gen\vectors.json", encoding="utf-8"))
cases = vec["sm3_cases"]

lines = []
lines.append("// 本文件由 gen/gen_sm3_tests.py 自动生成")
lines.append("// 测试向量来源：Python gmssl 库（其实现已通过 GB/T 32905-2016 国标向量验证）")
lines.append("// 共 %d 条向量：覆盖空消息、长度 55/56/57/63/64/65 填充边界、UTF-8 中文、0-700 字节随机消息" % len(cases))
lines.append("")
lines.append("///|")
lines.append("let sm3_msg_vectors : Array[(String, String)] = [")
for c in cases:
    lines.append('  ("%s", "%s"),' % (c["hex"], c["digest"]))
lines.append("]")
lines.append("")
lines.append("///|")
lines.append("fn sm3_hex_bytes(s : String) -> Bytes {")
lines.append("  @hexutil.decode(s).unwrap()")
lines.append("}")
lines.append("")
lines.append("///|")
lines.append('test "sm3 all cross-verified vectors (one-shot)" {')
lines.append("  for i, case in sm3_msg_vectors {")
lines.append("    let (msg_hex, want) = case")
lines.append("    let got = @sm3.hex_digest(sm3_hex_bytes(msg_hex))")
lines.append("    assert_eq(got, want, msg=\"vector #\\{i} mismatch\")")
lines.append("  }")
lines.append("}")
lines.append("")
lines.append("///|")
lines.append('test "sm3 streaming update equals one-shot" {')
lines.append("  for i, case in sm3_msg_vectors {")
lines.append("    let (msg_hex, want) = case")
lines.append("    let data = sm3_hex_bytes(msg_hex)")
lines.append("    // 按与向量序号相关的位置切分，模拟真实流式输入")
lines.append("    let cut = if data.length() == 0 { 0 } else { i % (data.length() + 1) }")
lines.append("    let h = @sm3.Sm3::new()")
lines.append("    h.update(data[0:cut].to_owned())")
lines.append("    h.update(data[cut:data.length()].to_owned())")
lines.append("    assert_eq(@hexutil.encode(h.finalize()), want, msg=\"streaming #\\{i} mismatch\")")
lines.append("  }")
lines.append("}")
lines.append("")
lines.append("///|")
lines.append('test "sm3 many small updates equals one-shot" {')
lines.append("  for i, case in sm3_msg_vectors {")
lines.append("    let (msg_hex, want) = case")
lines.append("    let data = sm3_hex_bytes(msg_hex)")
lines.append("    let h = @sm3.Sm3::new()")
lines.append("    for j in 0..<data.length() {")
lines.append("      h.update(data[j:j + 1].to_owned())")
lines.append("    }")
lines.append("    assert_eq(@hexutil.encode(h.finalize()), want, msg=\"byte-wise #\\{i} mismatch\")")
lines.append("  }")
lines.append("}")
lines.append("")
lines.append("///|")
lines.append('test "sm3 reset reuses hasher correctly" {')
lines.append("  for i, case in sm3_msg_vectors {")
lines.append("    let (msg_hex, want) = case")
lines.append("    let h = @sm3.Sm3::new()")
lines.append("    h.update(sm3_hex_bytes(\"deadbeef\"))")
lines.append("    h.reset()")
lines.append("    h.update(sm3_hex_bytes(msg_hex))")
lines.append("    assert_eq(@hexutil.encode(h.finalize()), want, msg=\"reset #\\{i} mismatch\")")
lines.append("  }")
lines.append("}")
lines.append("")

out = r"C:\Users\16841\WorkBuddy\2026-09-17-21-36-22\smcrypto\sm3\sm3_vectors_test.mbt"
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("written", out, len(cases), "vectors")
